int tp28xx_read_register(uint32_t i2c_fd, unsigned int addr, unsigned int *data)
{
    return ar_hal_i2c_master_read(i2c_fd, VG_TP2803_I2C_ADDRESS,
                                  8, &addr, 1, data, 1);
}

int tp28xx_write_register(uint32_t i2c_fd, unsigned int addr, unsigned int data)
{
    unsigned char buf[8];

    buf[0] = (unsigned char)addr;
    buf[1] = (unsigned char)data;

    return ar_hal_i2c_master_write(i2c_fd, VG_TP2803_I2C_ADDRESS, 8, buf, 2);
}

int tp28xx_poweron(uint32_t uGpioGroup, uint32_t uGpioPort, uint32_t uGpioId)
{
    int reset_gpio = ar_hal_gpio_name_to_num(uGpioGroup, uGpioPort, uGpioId);
    printf("tp2803_power_on: reset_gpio = %d\n", reset_gpio);

    ar_hal_gpio_export(reset_gpio);
    ar_hal_gpio_set_dir(reset_gpio, 1); // set the gpio dir to out

    ar_hal_gpio_set_value(reset_gpio, 0);
    usleep(5000);
    ar_hal_gpio_set_value(reset_gpio, 1);
    usleep(5000);
    return 0;
}

int tp29xx_poweroff(uint32_t uGpioGroup, uint32_t uGpioPort, uint32_t uGpioId)
{
    int reset_gpio = ar_hal_gpio_name_to_num(uGpioGroup, uGpioPort, uGpioId);
    printf("tp9930_power_off: reset_gpio = %d\n", reset_gpio);
    ar_hal_gpio_export(reset_gpio);
    ar_hal_gpio_set_dir(reset_gpio, 1); // set the gpio dir to out
    ar_hal_gpio_set_value(reset_gpio, 0);
    return 0;
}

void TP29xx_Reg_init(uint32_t i2c_fd, const unsigned char *RegSet)
{
    int i = 0;
    unsigned int index, val;

    while (*(RegSet + i) != 0xFE)
    {
        index = *(RegSet + i);
        val = *(RegSet + i + 1);
        tp28xx_write_register(i2c_fd, index, val);
        i += 2;
    }
}

int tp2803_i2c_init(uint32_t i2cbus, uint32_t vomode)
{
    int i2cfd = ar_hal_i2c_open(i2cbus);
    if (i2cfd < 0)
    {
        printf("open i2c bus[%d],failed\n", i2cbus);
        return -1;
    }
    uint32_t devid_0 = 0, devid_1 = 0;
    tp28xx_read_register(i2cfd, 0xfe, &devid_0);
    tp28xx_read_register(i2cfd, 0xff, &devid_1);
    printf("TP28xx id: %02x %02x\n", devid_0, devid_1);
    if (enum_tp2803_vo_ahd1080p30 == vomode)
    {

        TP29xx_Reg_init(i2cfd, Tp2803_bt1120_ahd1080p30_dataset);
    }
    else
    {
        printf("TP29xx_Reg_init\n");
        TP29xx_Reg_init(i2cfd, Tp2803_bt1120_ahd1080p25_dataset);
    }
    ar_hal_i2c_close(i2cfd);
    return 0;
}

int tp28xx_init(tp28xx_dev_attr attr)
{
    if (pthread_mutex_trylock(&g_dDevmuetx) != 0)
    {
        printf("tp28xx in use!!!\n");
        return 0;
    }
    g_DaDevAttr = attr;
    printf("uGpioGroup=%d uGpioPort=%d uGpioId=%d i2cbus=%d vomode=%d\n", attr.uGpioGroup, attr.uGpioPort, attr.uGpioId, attr.i2cbus, attr.vomode);
    tp28xx_poweron(attr.uGpioGroup, attr.uGpioPort, attr.uGpioId);
    
    //system("devmem 0x01070060 32 0xffffeeee"); //mclk 27M
    ar_hal_clk_set_rate(CLK_SENSOR1,27000); //sensor_clk1
	ar_hal_clk_enable_byid(CLK_SENSOR1);

    if (tp2803_i2c_init(attr.i2cbus, attr.vomode) < 0)
    {
        tp29xx_poweroff(attr.uGpioGroup, attr.uGpioPort, attr.uGpioId);
        return -1;
    }
    return 0;
}

