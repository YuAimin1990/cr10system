static int tp28xx_read_register(uint32_t i2c_fd, unsigned int addr, unsigned int *data);
static int tp28xx_write_register(uint32_t i2c_fd, unsigned int addr, unsigned int data);

static int tp28xx_poweron(uint32_t uGpioGroup, uint32_t uGpioPort, uint32_t uGpioId);
